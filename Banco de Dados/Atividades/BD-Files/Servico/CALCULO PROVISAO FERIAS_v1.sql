SELECT
	F.COD_FUNC AS COD
,	F.NOME AS FUNCIONARIO
,	ROUND(SUM(E.VR_PROCESSADO), 2) + (SELECT FIRST 1 SALARIO FROM FPHSTSAL SAL WHERE SAL.COD_FUNC = F.COD_FUNC ORDER BY DTA_ALTER DESC ) AS BASE
,	ROUND((SUM(E.VR_PROCESSADO)/12)+((SUM(E.VR_PROCESSADO)/12)/3), 2) AS TOTAL
,	ROUND(((SUM(E.VR_PROCESSADO)/12 + ((SUM(E.VR_PROCESSADO)/12)/3))/100*8), 2) AS FGTS
FROM
	FPFICHA_EVENTO E, FPFUNC F, FPEVENTO CE--, FPHSTSAL SAL
WHERE
	E.ID_EVENTO IN (SELECT ID_EVENTO FROM FPEVENTO WHERE COD_EVENTO IN (2,13,33,81,82,85,86,87,89,91,92,93,96,97,98,99,102,104,105,106,108,113,114,118,121,123,125,126,128,132,137,143,155,157,172,173,195,196,204,205,
206,208,213,220,223,224,225,228,229,233,236,237,240,245,248) )
	-- AND F.COD_SIT <> 'D' -- RETIRADO POR SOLICITAÇÃO DA JULIANY
	AND E.ID_REMESSA IN (SELECT ID_REMESSA FROM FPREMESSA WHERE ANO_PROC = :ANO AND MES_PROC = :MES ORDER BY ID_REMESSA ASC)
	AND E.COD_FUNC = F.COD_FUNC
	AND E.ID_EVENTO = CE.ID_EVENTO
	--AND F.COD_FUNC = SAL.COD_FUNC 
	AND F.COD_FUNC BETWEEN :COD_INICIAL AND :COD_FINAL
    AND F.COD_FUNC IN (SELECT COD_FUNC FROM FPHSTSIT WHERE EXTRACT(MONTH FROM DTA_ALTER) = :MES AND EXTRACT(YEAR FROM DTA_ALTER) = :ANO AND COD_SIT = 'F')
    AND F.COD_FUNC = 1005
GROUP BY
	F.COD_FUNC, F.NOME
ORDER BY
	F.NOME ASC;

